"""Generate the rsyslog drop-in and nftables rules from the device inventory.

rsyslog (not netrescale) listens on 514/tcp: it keeps queueing to disk while netrescale
restarts and needs no extra privileges in our service. Files are keyed by the sender's IP
($fromhost-ip), never by the hostname inside the message, which an attacker could forge.
Senders that aren't in the inventory go to a quarantine file.
"""

from __future__ import annotations

from netrescale.config import Config

SYSLOG_ROOT = "/var/log/netrescale/syslog"


def syslog_sources(cfg: Config) -> list[str]:
    ips: list[str] = []
    for d in cfg.devices:
        for ip in [d.nsip, *d.syslog_sources]:
            if ip not in ips:
                ips.append(ip)
    return ips


def rsyslog_conf(cfg: Config, port: int = 514) -> str:
    ips = syslog_sources(cfg)
    cond = " or ".join(f'$fromhost-ip == "{ip}"' for ip in ips) or "0 == 1"
    return f"""\
# /etc/rsyslog.d/60-netrescale.conf - generated by `netrescale rsyslog-config`; regenerate
# after changing devices in /etc/netrescale/config.yaml. Requires imtcp not to be loaded
# elsewhere (Ubuntu ships it commented out in /etc/rsyslog.conf).
module(load="imtcp" MaxSessions="500")

template(name="NetrescaleFile" type="string"
         string="{cfg.paths.log_dir}/syslog/%fromhost-ip%/%$year%-%$month%-%$day%.log")
template(name="NetrescaleLine" type="string"
         string="%timegenerated:::date-rfc3339% %fromhost-ip% %rawmsg%\\n")

ruleset(name="netrescale"
        queue.type="LinkedList" queue.filename="netrescale" queue.size="200000"
        queue.maxDiskSpace="4g" queue.saveOnShutdown="on") {{
  if ({cond}) then {{
    action(type="omfile" dynaFile="NetrescaleFile" template="NetrescaleLine"
           dynaFileCacheSize="64" fileOwner="syslog" fileGroup="netrescale"
           fileCreateMode="0640" dirCreateMode="0770" dirOwner="syslog" dirGroup="netrescale"
           asyncWriting="on" flushOnTXEnd="on" ioBufferSize="256k")
  }} else {{
    action(type="omfile" file="{cfg.paths.log_dir}/syslog/quarantine.log" template="NetrescaleLine"
           fileOwner="syslog" fileGroup="netrescale" fileCreateMode="0640")
  }}
  stop
}}

input(type="imtcp" port="{port}" ruleset="netrescale")
"""


def nftables_conf(cfg: Config, port: int = 514) -> str:
    v4 = [ip for ip in syslog_sources(cfg) if ":" not in ip]
    v6 = [ip for ip in syslog_sources(cfg) if ":" in ip]
    elems4 = ", ".join(v4) or "127.0.0.1"
    elems6 = ", ".join(v6) or "::1"
    return f"""\
# /etc/nftables.d/netrescale.nft - generated by `netrescale rsyslog-config --nft`.
# Only inventory NetScalers may send syslog to this server.
table inet netrescale {{
  set ns_v4 {{ type ipv4_addr; elements = {{ {elems4} }} }}
  set ns_v6 {{ type ipv6_addr; elements = {{ {elems6} }} }}
  chain input {{
    type filter hook input priority filter; policy accept;
    tcp dport {port} ip saddr @ns_v4 accept
    tcp dport {port} ip6 saddr @ns_v6 accept
    tcp dport {port} drop
    udp dport {port} drop
  }}
}}
"""
